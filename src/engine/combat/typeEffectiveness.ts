export function getTypeMultiplier(attackType: number, defendTypes: number[]): number {
  if (defendTypes.length === 0) {
    return 1;
  }

  let multiplier = 1;
  const attackModifiers = TYPE_CHART[attackType] || {};

  for (const defendType of defendTypes) {
    const modifier = attackModifiers[defendType];
    if (modifier !== undefined) {
      multiplier *= modifier;
    }
  }

  return multiplier;
}
